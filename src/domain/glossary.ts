/** The terms in alphabetical order, ignoring case and punctuation. */
export const GLOSSARY: readonly GlossaryTerm[] = [...RAW].sort((a, b) => a.term.localeCompare(b.term, 'en', { sensitivity: 'base', ignorePunctuation: true }))

/** The glossary grouped under the first letter of each term, in order. */
export function glossaryByLetter(list: readonly GlossaryTerm[] = GLOSSARY): { letter: string; terms: GlossaryTerm[] }[] {
  const groups: { letter: string; terms: GlossaryTerm[] }[] = []
  for (const g of list) {
    const letter = g.term.charAt(0).toUpperCase()
    const last = groups[groups.length - 1]
    if (last && last.letter === letter) last.terms.push(g)
    else groups.push({ letter, terms: [g] })
  }
  return groups
}
