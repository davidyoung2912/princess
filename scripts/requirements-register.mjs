// Builds docs/requirements-clauses.md: every acceptance clause of the best-in-market requirements document,
// with the matrix status and, where a probe is written in docs/requirements-probes.tsv, whether the evidence is present.
// A probe is a search, not a proof: "found" means the wording or state exists somewhere; "absent" is a gap candidate.
// Run: node scripts/requirements-register.mjs   (writes the file; add --check to print totals only)
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const rd = (p) => readFileSync(join(root, p), 'utf8')

const ID = /^[A-Z][A-Z0-9]{1,3}-\d\d$/
const cells = (line) => line.trim().replace(/^\||\|$/g, '').split('|').map((x) => x.trim())

const rows = new Map()
for (const line of rd('docs/princess_cruises_expanded_best_in_market_requirements.md').split('\n')) {
  if (!line.startsWith('|')) continue
  const c = cells(line)
  if (!ID.test(c[0]) || c.length < 3 || rows.has(c[0])) continue
  const acc = c.length > 3 ? c[3] : c[2]
  rows.set(c[0], { id: c[0], pri: c[1], req: c[2], acc, clauses: acc.split(/(?<=[.;])\s+/).map((s) => s.trim()).filter((s) => s.length > 3) })
}
const matrix = new Map()
for (const line of rd('docs/best-in-market-matrix.md').split('\n')) {
  if (!line.startsWith('|')) continue
  const c = cells(line)
  if (ID.test(c[0]) && c.length === 6) matrix.set(c[0], { status: c[2], gap: c[5] })
}

const SKIP = /(^|\/)(node_modules|dist|bin|obj|testing)(\/|$)|\.test\.|\.json$/
function walk(dir, out = []) {
  for (const n of readdirSync(join(root, dir))) {
    const p = `${dir}/${n}`
    if (SKIP.test(p)) continue
    const s = statSync(join(root, p))
    if (s.isDirectory()) walk(p, out)
    else if (/\.(ts|tsx|cs|css)$/.test(n) || n === 'en.ts') out.push(p)
  }
  return out
}
const srcFiles = walk('src'), serverFiles = walk('server/Princess.Api')
const EN = 'src/i18n/locales/en.ts'
const cache = new Map()
const text = (p) => cache.get(p) ?? (cache.set(p, rd(p)), cache.get(p))

// 'src' and 'any' leave out the English strings file and the assistant's canned answers (src/ai), which mention almost everything.
// Use 'en' to look for wording in the strings file, or a path (comma separated list allowed) to look in particular files.
const plain = (f) => f !== EN && !f.startsWith('src/ai/')
function filesFor(scope) {
  return scope.split(',').flatMap((one) => {
    if (one === 'en') return [EN]
    if (one === 'any') return [...srcFiles, ...serverFiles].filter(plain)
    if (one === 'src') return srcFiles.filter(plain)
    if (one === 'server') return serverFiles
    const p = one.replace(/\/$/, '')
    if (!existsSync(join(root, p))) return []
    return statSync(join(root, p)).isDirectory() ? [...srcFiles, ...serverFiles].filter((f) => f.startsWith(`${p}/`)) : [p]
  })
}

const probes = []
for (const line of rd('docs/requirements-probes.tsv').split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue
  const [id, label, re, scope = 'any'] = line.split('\t')
  if (!rows.has(id)) throw new Error(`probe for unknown id ${id}`)
  let rx
  try { rx = new RegExp(re, 'i') } catch { throw new Error(`bad regex for ${id}: ${re}`) }
  const hits = []
  for (const f of filesFor(scope)) if (rx.test(text(f))) hits.push(f)
  probes.push({ id, label, scope, hits })
}

if (process.argv.includes('--explain')) {
  // For each absent probe, show where the same words appear anywhere (strings file and assistant answers included), to help a person decide.
  for (const p of probes.filter((x) => !x.hits.length)) {
    const line = rd('docs/requirements-probes.tsv').split('\n').find((l) => l.startsWith(`${p.id}\t${p.label}`))
    const rx = new RegExp(line.split('\t')[2], 'i')
    const found = []
    for (const f of [...srcFiles, ...serverFiles]) {
      const ls = text(f).split('\n')
      for (let i = 0; i < ls.length && found.length < 3; i++) if (rx.test(ls[i])) found.push(`${f}:${i + 1}: ${ls[i].trim().slice(0, 110)}`)
    }
    console.log(`\n${p.id} ${p.label}\n  ${found.join('\n  ') || '(nothing anywhere)'}`)
  }
  process.exit(0)
}
const verdicts = new Map()
for (const line of rd('docs/requirements-verdicts.tsv').split('\n')) {
  if (!line.trim() || line.startsWith('#')) continue
  const [id, v, note] = line.split('\t')
  if (!rows.has(id)) throw new Error(`verdict for unknown id ${id}`)
  verdicts.set(id, { v, note })
}
const byId = new Map()
for (const p of probes) (byId.get(p.id) ?? byId.set(p.id, []).get(p.id)).push(p)

const total = [...rows.values()].reduce((n, r) => n + r.clauses.length, 0)
const found = probes.filter((p) => p.hits.length), absent = probes.filter((p) => !p.hits.length)
const out = []
out.push('# Requirement clause register (BM16)', '')
out.push('Generated by `node scripts/requirements-register.mjs` from `docs/princess_cruises_expanded_best_in_market_requirements.md`, `docs/best-in-market-matrix.md` and `docs/requirements-probes.tsv`. Do not edit by hand; edit the probes and re-run.', '')
out.push('**How to read it.** A probe is a search written for one clause. `found` means the wording or state exists in the named place; it does **not** prove the behaviour is right. `ABSENT` means the search found nothing where the feature should be: a gap candidate that a person must confirm by reading. `unread` means no probe is written yet.', '')
out.push(`Judged by a person: ${verdicts.size} requirements (${[...verdicts.values()].filter((d) => d.v === 'GAP').length} gap, ${[...verdicts.values()].filter((d) => d.v === 'PARTIAL').length} partial, ${[...verdicts.values()].filter((d) => d.v === 'NEEDS-READ').length} still to read).`, '')
out.push(`Totals: ${rows.size} requirements, ${total} clauses, ${probes.length} probes (${found.length} found, ${absent.length} absent).`, '')
out.push('## Gap candidates (probe absent)', '', '| ID | Pri | Matrix says | Clause searched | Searched in |', '|---|---|---|---|---|')
for (const p of absent) out.push(`| ${p.id} | ${rows.get(p.id).pri} | ${matrix.get(p.id)?.status ?? '?'} | ${p.label} | \`${p.scope}\` |`)
out.push('', '## Read and judged by a person', '', '| ID | Pri | Matrix says | Verdict | What was found |', '|---|---|---|---|---|')
for (const [id, d] of verdicts) out.push(`| ${id} | ${rows.get(id).pri} | ${matrix.get(id)?.status ?? '?'} | **${d.v}** | ${d.note} |`)
out.push('', '## Every clause', '')
out.push('| ID | Pri | Matrix | Clause | Probe |', '|---|---|---|---|---|')
for (const r of rows.values()) {
  const ps = byId.get(r.id) ?? []
  r.clauses.forEach((c, i) => {
    const mark = i === 0 && ps.length ? ps.map((p) => `${p.hits.length ? 'found' : '**ABSENT**'}: ${p.label}${p.hits.length ? ` (\`${relative('', p.hits[0])}\`)` : ''}`).join('<br>') : i === 0 ? 'unread' : ''
    out.push(`| ${r.id}#${i + 1} | ${r.pri} | ${matrix.get(r.id)?.status ?? '?'} | ${c.replace(/\|/g, '/')} | ${mark} |`)
  })
}
if (!process.argv.includes('--check')) writeFileSync(join(root, 'docs/requirements-clauses.md'), `${out.join('\n')}\n`)
console.log(out.find((l) => l.startsWith('Totals')))
